import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
import {dates,normalize} from '../experiments/date-mobile-build/date-parser.js';
import {resolveDateOrders} from '../experiments/date-mobile-build/date-order.js';
const Roles=createRequire(import.meta.url)('../experiments/date-mobile-build/date-roles.cjs');
const line=(text,y=0)=>({text:normalize(text),confidence:.99,bbox:[0,y,300,y+20],parsed_dates:dates(normalize(text))});
const select=lines=>Roles.select(resolveDateOrders({id:'constructed',width:600,height:600,lines}).raw);
let p=select([line('PRO:14.09.2027'),line('EXP:14.10.2028',40)]);
assert.deepEqual(p.candidates.map(c=>c.role),['manufactured','expiry']);assert.equal(p.strict_expiry.date,'2028-10-14');
p=select([line('Best before',0),line('2027.11.12',30),line('Batch no.:1306',55)]);
assert.equal(p.strict_expiry.date,'2027-11-12');assert.equal(p.suggestion.role,'best_before');
p=select([line('LOT 14.09.2027')]);assert.equal(p.suggestion,null);assert.equal(p.candidates[0].role,'batch');
p=select([line('Batch',0),line('2027.11.12',30)]);assert.equal(p.strict_expiry,null);assert.equal(p.candidates[0].role,'unknown');
for(const cue of ['Best if used by','BESTIFUSEDBY','Best used by'])assert.equal(select([line(cue+' 14.09.2027')]).suggestion.role,'best_before',cue);
assert.equal(select([line('USE BY 14.09.2027')]).suggestion.role,'use_by');
assert.equal(select([line('EXPDATE:14.09.2027')]).suggestion.role,'expiry');
assert.equal(select([line('PROTEIN 14.09.2027')]).suggestion.role,'unknown');
assert.equal(select([line('PRO 14.09.2027')]).suggestion.role,'unknown');
assert.equal(select([line('11.09.2021')]).suggestion,null);
assert.equal(select([line('20200624'),line('20210824',40)]).suggestion,null);
assert.deepEqual(dates('2021:02.25').map(c=>c.date),['2021-02-25']);
for(const t of ['2021:02.30','20:21:02','2022.11.1 4'])assert.deepEqual(dates(t),[],t);
const box={document:{getElementById:()=>null,addEventListener:()=>{},readyState:'complete'},setTimeout:()=>0,console};box.window=box;vm.createContext(box);
for(const f of ['date-token-guard-v1.js','date-policy-v1.js','expiry-camera-v1.js'])vm.runInContext(fs.readFileSync(f,'utf8'),box);
assert.equal(box.RESERVE_EXPIRY_CAMERA.parseDate('2021:02.25'),'2021-02-25');
for(const cue of ['BEST IF USED BY','BESTIFUSEDBY']){const t=cue+' 14.09.2027';assert.equal(box.RESERVE_DATE_POLICY.infer(t,cue.length+1,10),'best_before');}
assert.equal(box.RESERVE_DATE_POLICY.infer('PRO: 14.09.2027',5,10),'manufactured');
assert.equal(box.RESERVE_DATE_POLICY.infer('Use by 14.09.2027',7,10),'use_by');
console.log('Open-case regressions: explicit production/expiry and best-if-used-by cues, separate batch codes, complete YMD colons; ambiguity and conflicting dates remain open. Constructed cases, not accuracy evidence.');
