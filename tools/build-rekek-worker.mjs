// Deterministic, dependency-free bundle for Cloudflare's single-file editor.
import fs from 'node:fs';
const files = ['services/rekek-vision/extraction.mjs', 'services/rekek-vision/route.mjs',
  'services/reserve-worker/expiry.mjs', 'services/reserve-worker/worker.mjs'];
const body = files.map(path => `// ${path}\n` + fs.readFileSync(path, 'utf8')
  .replace(/^import .+;\r?\n/gm, '').replace(/^export (?!default)/gm, '')).join('\n');
const output = '// GENERATED by node tools/build-rekek-worker.mjs; edit the source modules.\n' + body;
const destination = 'services/reserve-worker/worker.js';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Worker bundle is stale');
} else fs.writeFileSync(destination, output);
