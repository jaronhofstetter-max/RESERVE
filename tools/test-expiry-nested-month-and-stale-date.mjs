import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const sandbox={window:{},document:{getElementById:()=>null},setTimeout:()=>0,console};
sandbox.window=sandbox;
vm.createContext(sandbox);vm.runInContext(fs.readFileSync('expiry-camera-v1.js','utf8'),sandbox);
const api=sandbox.RESERVE_EXPIRY_CAMERA;
const full=api.candidates('MHD 14.09.2022');
assert(full.some(x=>x.date==='2022-09-14'&&x.kind==='day'));
assert(!full.some(x=>x.kind==='month'),'A full printed day must not also vote for a nested month');
assert.equal(api.selectConsensus(['MHD 14.09.2022','MHD 09.2022']).votes,1,'Partial and complete dates must not manufacture month consensus');
assert.equal(api.parseDate('Mindestens haltbar bis Ende 09.2022'),'2022-09-30');
assert(api.candidates('MHD 14.09.2022; anderes Produkt: MHD 10.2023').some(x=>x.kind==='month'&&x.date==='2023-10-31'));
const field={type:'date',value:'',validity:{valid:true},dataset:{effectiveDate:'2027-03-11',datePrecision:'day'}};
assert.equal(api.effectiveDateForInput(field),'','A cleared field must never resolve to its previous date');
api.manualDateChanged(field);
assert.equal(field.dataset.effectiveDate,undefined);assert.equal(field.dataset.datePrecision,undefined);
field.value='2026-11-05';api.manualDateChanged(field);
assert.equal(api.effectiveDateForInput(field),'2026-11-05');
field.validity.valid=false;api.manualDateChanged(field);
assert.equal(api.effectiveDateForInput(field),'');assert.equal(field.dataset.effectiveDate,undefined);
assert.equal(api.effectiveDateForInput({type:'month',value:'2028-02',dataset:{}}),'2028-02-29');
console.log('Expiry nested-month and stale-date regressions: OK');
